from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Any

from harness.engine.common import load_json
from harness.engine.common import redact_path

PROJECT_VERSION = "0.4.0"
PROVENANCE_NOTE = (
    "\n---\n"
    "_This report was generated by the deterministic tool-compile-debug engine "
    "(engine version {version}). Treat recommendations as evidence to review and "
    "confirm them with a successful build._\n"
)


def _provenance_note() -> str:
    """Return deterministic provenance text for the generated report."""
    return PROVENANCE_NOTE.format(version=PROJECT_VERSION)


def _display_log_path(log_path: str | None) -> str:
    if not log_path:
        return ""
    normalized = str(log_path).replace("\\", "/")
    marker = "logs/probes/"
    if marker in normalized:
        return normalized[normalized.index(marker) :]
    redacted = redact_path(str(log_path))
    if redacted == str(log_path) and (
        normalized.startswith("/") or re.match(r"^[A-Za-z]:/", normalized)
    ):
        return Path(log_path).name
    return redacted


def _format_seconds(value: Any) -> str:
    if value is None or value == "":
        return ""
    try:
        return f"{float(value):.2f}s"
    except (TypeError, ValueError):
        return ""


_EXECUTED_PROBE_STATUSES = frozenset({"passed", "failed"})
_PROBE_TARGETS = {
    "probe_direct_kernel_compile": "captured kernel compile command",
    "probe_preprocess_only": "preprocess-only command",
    "probe_O0": "low-optimization compile",
    "probe_O2": "optimized compile",
    "probe_O3": "optimized compile",
}


def _probe_meaning(probe: dict[str, Any]) -> str:
    """Render probe rows as supplied observations, never as causal claims.

    A probe runs an isolated replay of a captured command; without verified
    same-TU/source/recipe binding it cannot reproduce, avoid or localize the
    original failure, and non-executed statuses must not read as outcomes.
    """
    status = probe.get("status")
    if status == "timeout":
        return "Probe timed out; no executed outcome. Build logs remain the primary evidence."
    if status not in _EXECUTED_PROBE_STATUSES:
        reason = probe.get("reason")
        suffix = f" reason={reason}" if reason else ""
        return (
            f"Not executed; status `{status}`.{suffix} No compile outcome is claimed."
        )
    target = _PROBE_TARGETS.get(str(probe.get("name")), "probe command")
    outcome = "exited with errors" if status == "failed" else "exited successfully"
    return (
        f"Isolated replay {outcome} ({target}). Supplied observation only; "
        "task binding to this failure is unverified — confirm TU, source and recipe before interpreting."
    )


def _compiler_probe_rows(probes: dict[str, Any] | None) -> list[dict[str, str]]:
    if not probes:
        return []
    names = {
        "probe_direct_kernel_compile",
        "probe_preprocess_only",
        "probe_O0",
        "probe_O2",
        "probe_O3",
    }
    rows: list[dict[str, str]] = []
    for probe in probes.get("probes") or []:
        if probe.get("name") not in names:
            continue
        rows.append(
            {
                "name": str(probe.get("name")),
                "status": str(probe.get("status") or "unknown"),
                "meaning": _probe_meaning(probe),
                "elapsed": _format_seconds(probe.get("elapsed_s")),
                "timeout": _format_seconds(probe.get("timeout_s")),
                "log": _display_log_path(probe.get("log_path")),
            }
        )
    return rows


def write_report(
    case_dir: Path,
    diagnosis: dict[str, Any],
    suggestions: dict[str, Any] | None,
    verify: dict[str, Any] | None,
    md_out: Path,
    probes: dict[str, Any] | None = None,
    env: dict[str, Any] | None = None,
) -> None:
    suggestions = suggestions or {}
    verify = verify or {}
    meta = load_json(case_dir / "meta.json", default={})
    primary = diagnosis.get("primary_error") or {}
    lines: list[str] = []
    title = meta.get("case_id") or case_dir.name
    lines.append(f"# 编译失败诊断报告：{title}\n")
    lines.append("## 1. 结论\n")
    lines.append((diagnosis.get("summary") or "暂无结论。") + "\n")
    lines.append("## 2. 主错误\n")
    if primary:
        location = primary.get("file") or ""
        if primary.get("line"):
            location += f":{primary.get('line')}"
        lines.append(f"- message: {primary.get('message')}\n")
        lines.append(
            f"- location: {redact_path(location) if location else 'unknown'}\n"
        )
        lines.append(f"- signature: {diagnosis.get('status', 'unknown')}\n")
    else:
        lines.append("未找到明确主错误。\n")
    lines.append("## 3. 编译阶段与分类\n")
    lines.append(f"- phase（兼容推断）: {diagnosis.get('phase')}\n")
    lines.append(f"- category: {diagnosis.get('category')}\n")
    for axis in ("failure_stage", "source_context", "path_hint"):
        evidence = diagnosis.get(axis) or {}
        if evidence:
            lines.append(
                f"- {axis}: {evidence.get('value')} (basis={evidence.get('basis')})\n"
            )
            if evidence.get("blockers"):
                lines.append(f"  - 未确认原因: {', '.join(evidence['blockers'])}\n")
    for conflict in diagnosis.get("conflicts") or []:
        lines.append(
            f"- 证据冲突: {' / '.join(conflict['axes'])}: "
            f"{' / '.join(conflict['values'])} ({conflict['reason']})\n"
        )
    facts = diagnosis.get("diagnostic_facts") or {}
    if facts:
        mechanism = facts.get("mechanism") or {}
        association = facts.get("sdk_association") or {}
        lines.append(
            f"- 语言/工具机制: {mechanism.get('value')} (basis={mechanism.get('basis')})\n"
        )
        lines.append(
            f"- SDK关联证据: {association.get('status')} (basis={association.get('basis')})\n"
        )
        lines.append(
            "  - namespace或声明关联不证明版本/目标适用、API存在或替换已验证。\n"
        )
    lines.append("## 4. 证据\n")
    for cand in (diagnosis.get("root_cause_candidates") or [])[:5]:
        lines.append(
            f"- rank {cand.get('rank')}: {cand.get('cause')} (confidence={cand.get('confidence')})\n"
        )
        for ev in (cand.get("evidence") or [])[:3]:
            lines.append(f"  - {redact_path(str(ev))}\n")
    lines.append("## 5. 根因候选\n")
    for cand in (diagnosis.get("root_cause_candidates") or [])[:5]:
        files = ", ".join(
            f"{f.get('path')}:{f.get('line')}" if f.get("line") else str(f.get("path"))
            for f in cand.get("files", [])
            if f.get("path")
        )
        lines.append(
            f"- {cand.get('rank')}. {cand.get('cause')} {f'({redact_path(files)})' if files else ''}\n"
        )
    rows = _compiler_probe_rows(probes)
    if rows:
        lines.append("## 6. Compiler Probe Evidence\n")
        lines.append(
            "以下为传入或隔离重放的探针观察；与本次失败的同TU/源码/配方绑定未核，不构成对原构建失败的因果证明。\n"
        )
        lines.append("| Probe | Status | Meaning | Elapsed | Timeout | Log |\n")
        lines.append("|---|---|---|---:|---:|---|\n")
        for row in rows:
            log_cell = f"`{row['log']}`" if row["log"] else ""
            elapsed_cell = f"`{row['elapsed']}`" if row["elapsed"] else ""
            timeout_cell = f"`{row['timeout']}`" if row["timeout"] else ""
            lines.append(
                f"| `{row['name']}` | `{row['status']}` | {row['meaning']} | "
                f"{elapsed_cell} | {timeout_cell} | {log_cell} |\n"
            )
    lines.append("## 7. 修复建议\n")
    for suggestion in suggestions.get("suggestions", []):
        lines.append(
            f"- {suggestion.get('rank')}. {suggestion.get('title')} (risk={suggestion.get('risk')})\n"
        )
        if suggestion.get("action"):
            lines.append(f"  - action: {redact_path(str(suggestion['action']))}\n")
        for note in suggestion.get("compiler_notes") or []:
            location = f"{note.get('file_original')}:{note.get('line')}"
            lines.append(
                f"  - compiler note ({redact_path(location)}): {note.get('diagnostic')}\n"
            )
            if note.get("source_excerpt"):
                lines.append(
                    f"    - excerpt: `{redact_path(str(note['source_excerpt']))}`\n"
                )
        if suggestion.get("verification"):
            lines.append(
                f"  - verification: `{redact_path(str(suggestion.get('verification')))}`\n"
            )
    lines.append("## 8. 验证结果\n")
    if verify:
        lines.append(f"- transition: {verify.get('transition')}\n")
        lines.append(f"- before: {(verify.get('before') or {}).get('status')}\n")
        lines.append(f"- after: {(verify.get('after') or {}).get('status')}\n")
    else:
        lines.append("未运行验证。\n")
    lines.append("## 9. 后续风险\n")
    if diagnosis.get("is_compiler_internal_suspected"):
        lines.append(
            "- 内部异常怀疑不证明源码合法；先核更早的直接诊断和已有同状态证据，仅在需区分具体假设时补受控探针或缩减。\n"
        )
    else:
        lines.append("- 修复后仍需重新编译确认没有进入下一阶段错误。\n")
    lines.append("## 10. 附录：环境与命令\n")

    # Include the environment used to interpret version-dependent diagnostics.
    if env:
        cann = env.get("cann") or {}
        if cann.get("found"):
            lines.append(
                f"- CANN: version={cann.get('version')} path={cann.get('install_dir')}\n"
            )
        else:
            lines.append(
                "- CANN: 未找到（本机无 CANN 安装；诊断基于日志文本，仍有效）\n"
            )
        if env.get("soc"):
            lines.append(f"- SoC: {env.get('soc')}\n")
        npu = env.get("npu") or {}
        devices = npu.get("devices") or []
        if devices:
            lines.append(f"- NPU: 检测到 {len(devices)} 个设备（npu-smi）\n")
        for w in env.get("warnings") or []:
            lines.append(f"- 环境告警: {w}\n")
    if meta.get("repro_command"):
        lines.append(f"- repro: `{meta.get('repro_command')}`\n")
    for action in diagnosis.get("next_actions") or []:
        lines.append(f"- next: {action}\n")
    lines.append(_provenance_note())
    md_out.parent.mkdir(parents=True, exist_ok=True)
    md_out.write_text("".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Write a human-readable diagnosis report."
    )
    parser.add_argument("--case", required=True)
    parser.add_argument("--diagnosis", required=True)
    parser.add_argument("--patch-suggestions")
    parser.add_argument("--verify")
    parser.add_argument("--md-out", required=True)
    args = parser.parse_args()
    try:
        write_report(
            Path(args.case).resolve(),
            load_json(args.diagnosis, default={}),
            load_json(args.patch_suggestions, default={})
            if args.patch_suggestions
            else {},
            load_json(args.verify, default={}) if args.verify else {},
            Path(args.md_out),
        )
    except Exception as exc:  # noqa: BLE001 - CLI reports failures as an artifact
        Path(args.md_out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.md_out).write_text(
            f"# 编译失败诊断报告\n\n报告生成失败：{exc}\n", encoding="utf-8"
        )
        return 1
    print(str(Path(args.md_out)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
